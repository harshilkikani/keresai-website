  function safeGet(key) {
    try { return localStorage.getItem(key); } catch (_) { return null; }
  }
  function safeSet(key, val) {
    try { localStorage.setItem(key, val); } catch (_) { /* private mode / disabled storage */ }
  }

  function detectLang() {
    const saved = safeGet(STORAGE_KEY);
    if (saved && T[saved]) return saved;
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return T[nav] ? nav : 'en';
  }

  function t(key, lang) {
    const l = lang || current;
    return (T[l] && T[l][key]) || T.en[key] || key;
  }

  let current = 'en';

  function applyLang(lang) {
    if (!T[lang]) lang = 'en';
    current = lang;
    safeSet(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    if (LANGS[lang] && LANGS[lang].dir) document.documentElement.dir = LANGS[lang].dir;

    // Text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const value = t(key, lang);
      if (value !== undefined && value !== null) el.textContent = value;
    });
    // Attributes (placeholder, aria-label, title, content)
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      el.getAttribute('data-i18n-attr').split(';').forEach(pair => {
        const [attr, key] = pair.split(':').map(s => s.trim());
        if (attr && key) el.setAttribute(attr, t(key, lang));
      });
    });
    // Update meta title/description
    document.title = t('meta.title', lang);
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute('content', t('meta.description', lang));

    // Update lang switcher UI
    document.querySelectorAll('.lang-menu button').forEach(b => {
      b.setAttribute('aria-current', b.dataset.lang === lang ? 'true' : 'false');
    });
    const currentLabel = document.getElementById('lang-current');
    if (currentLabel) currentLabel.textContent = lang.toUpperCase();

    // Notify others
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }

  window.KeresI18n = {
    t,
    get current() { return current; },
    langs: LANGS,
    apply: applyLang,
    init: () => applyLang(detectLang())
  };

// Writes src/i18n/es.review.md: every Spanish string on the site as a
// key → Spanish table, grouped by page, for a native reviewer.
//   node scripts/export-es-review.mjs
// Bundles the TypeScript dictionaries with esbuild (already a dependency
// through Astro) so this stays a one-file script with no extra tooling.
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

process.env.KERES_ALLOW_MISSING = '1';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = path.join(root, 'node_modules', '.cache', 'es-review');
mkdirSync(tmp, { recursive: true });
const out = path.join(tmp, 'dicts.mjs');
await build({
  stdin: { contents: `export * as ui from './src/i18n/ui.ts'; export * as home from './src/i18n/home.ts'; export * as data from './src/i18n/data.es.ts';`, resolveDir: root, loader: 'ts' },
  bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'silent',
});
const { ui, home, data } = await import(pathToFileURL(out).href);

const SKIP_KEYS = new Set(['slug', 'path', 'href', 'kind', 'who', 'stage', 'id', 'industry', 'price', 'calc', 'mock', 'includedIn', 'n', 'color', 'd']);
const skipValue = (v) => /^(\/|https?:|mailto:)/.test(v) || /^[\d\s:.,–\-APM%$+×=()]+$/.test(v) || v.trim() === '';
const esc = (v) => v.replace(/\|/g, '\\|').replace(/\n/g, ' ');
function flatten(obj, prefix, rows) {
  if (typeof obj === 'string') { if (!skipValue(obj)) rows.push([prefix, obj]); return; }
  if (Array.isArray(obj)) { obj.forEach((v, i) => flatten(v, `${prefix}[${i}]`, rows)); return; }
  if (obj && typeof obj === 'object') { for (const [k, v] of Object.entries(obj)) { if (SKIP_KEYS.has(k)) continue; flatten(v, prefix ? `${prefix}.${k}` : k, rows); } }
}
const groups = [
  ['Chrome: nav, footer, sticky bar, skip link, honesty gate (every /es page)', { skip: ui.ui.es.skip, remiGate: ui.ui.es.remiGate, nav: ui.ui.es.nav, footer: ui.ui.es.footer, sticky: ui.ui.es.sticky }],
  ['Homepage /es', { home: home.home.es, stages: data.stages, agents: data.agents, foundServices: data.foundServices, heroTail: data.heroTail, writtenTo: data.writtenTo }],
  ['Quote form: /es/quote and embedded in every /es/go page', { form: ui.ui.es.form, quotePage: ui.ui.es.quotePage }],
  ['Ad landings /es/go, /es/go/home-services, /es/go/law, /es/go/dental', { go: ui.ui.es.go, goSteps: data.goSteps, goPages: data.goPages }],
  ['Website landings /es/go/website and the three verticals', { goWebsitePages: data.goWebsitePages, goWebsiteText: data.goWebsiteText }],
  ['Missed-call calculator (homepage and /es/go)', { calc: ui.ui.es.calc }],
  ['Mocks: example call, daily brief, agent bubbles, site-on-phone, Google listing (shared)', { mocks: ui.ui.es.mocks, transcripts: data.transcripts, briefs: data.briefs, agentMocks: data.agentMocks, siteMock: data.siteMock, siteMockText: data.siteMockText, listingMock: data.listingMock }],
];
let total = 0;
const md = [];
md.push('# Spanish copy for native review');
md.push('');
md.push('Generated by `node scripts/export-es-review.mjs` from `src/i18n/ui.ts`, `src/i18n/home.ts` and `src/i18n/data.es.ts`. Edit the source files, not this table; re-run the script after changes.');
md.push('');
md.push('## Three decisions before line edits');
md.push('');
md.push('1. **Tú or usted.** The whole site currently uses *tú* ("Cuéntanos quién eres", "tus llamadas", "Pedir cotización" is neutral). Owners of HVAC, plumbing, law and dental businesses in the US are the audience; Remi\'s example call uses *usted* with the caller. Decide one register for the site and one for Remi, and apply it everywhere.');
md.push('2. **Regional trade vocabulary.** Plomero vs fontanero; calefacción vs aire acondicionado vs climatización for HVAC; "techos" for roofing; "bufete" vs "despacho" for law firm; "sillón" for the dental chair. Pick the US-Spanish terms the target markets search for, not the Spain forms.');
md.push('3. **Does "Que te reserven." carry the weight of "Get booked."?** The H1 is "Que te encuentren. Que te contesten. Que te reserven." "Reservar" reads as hotel or restaurant in some markets; "Que te agenden." is the alternative used elsewhere in the copy ("agendar", "cita"). Choose one and align the verb across H1, doors and CTAs.');
md.push('');
for (const [title, obj] of groups) {
  const rows = []; flatten(obj, '', rows); total += rows.length;
  md.push(`## ${title}`); md.push(''); md.push(`${rows.length} strings`); md.push('');
  md.push('| key | Spanish |'); md.push('|---|---|');
  for (const [k, v] of rows) md.push(`| \`${k}\` | ${esc(v)} |`);
  md.push('');
}
md.splice(2, 0, `${total} strings across ${groups.length} groups. Every visible Spanish string comes from these three files; nothing on the /es pages is translated at runtime.`, '');
writeFileSync(path.join(root, 'src/i18n/es.review.md'), md.join('\n'));
console.log(`src/i18n/es.review.md: ${total} strings, ${groups.length} groups`);
